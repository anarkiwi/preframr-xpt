"""Emit the prodlike_4x train.list: top-N admitted composers plus a
composer whitelist (default {Goto80}), excluding eval-A SID files and
eval-B-held-out composers, sorted deterministically. Default N=100
yields ~26k SIDs (~5.9x prodlike).
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

DEFAULT_MANIFEST = "/scratch/preframr/corpus_index_full/manifest.parquet"
DEFAULT_PRODLIKE_DIR = "/scratch/anarkiwi/preframr/integration_tests/data/prodlike"
DEFAULT_OUT_DIR = "/scratch/anarkiwi/preframr/integration_tests/data/prodlike_4x"

EVAL_B_HOLDOUT_COMPOSERS = frozenset(
    {
        "Crisps",
        "Daglish_Ben",
        "Dobek_Eric",
        "Follin_Tim",
        "Marquis_Dave",
        "Mibri",
        "Wilson_Mark",
        "Winterberg_Michael",
    }
)

DEFAULT_INCLUDE_COMPOSERS = ("Goto80",)


def _composer_from_path(sid_path: str) -> str | None:
    parts = sid_path.split("/")
    if "MUSICIANS" in parts:
        i = parts.index("MUSICIANS")
        if len(parts) > i + 2:
            return parts[i + 2]
    return None


def _read_list(p: Path) -> list[str]:
    out = []
    for ln in p.read_text().splitlines():
        ln = ln.split("#", 1)[0].strip()
        if ln:
            out.append(ln)
    return out


def build(
    manifest_path: Path,
    prodlike_dir: Path,
    top_n: int,
    include_composers: tuple[str, ...],
) -> dict:
    m = pd.read_parquet(manifest_path)
    adm = m[~m["skipped_by_filter"]].copy()
    adm["composer_top"] = adm["sid_path"].map(_composer_from_path)
    adm = adm[adm["composer_top"].notna()]
    adm = adm[~adm["composer_top"].isin(EVAL_B_HOLDOUT_COMPOSERS)]

    eval_a_paths = set(_read_list(prodlike_dir / "eval-A.list"))
    eval_b_paths = set()
    for p in sorted(prodlike_dir.glob("eval-B-*.list")):
        for line in _read_list(p):
            eval_b_paths.add(line)
    held_out = eval_a_paths | eval_b_paths

    counts = adm.groupby("composer_top").size().sort_values(ascending=False)
    top_composers = set(counts.head(top_n).index)
    whitelist_added = [c for c in include_composers if c not in top_composers]
    selected = top_composers | set(include_composers)
    missing_whitelist = [c for c in include_composers if c not in counts.index]
    if missing_whitelist:
        raise ValueError(
            f"--include-composer values not present in admitted manifest: "
            f"{missing_whitelist}"
        )

    chosen = adm[adm["composer_top"].isin(selected)].copy()
    chosen["rel"] = chosen["sid_path"]
    chosen = chosen[~chosen["rel"].isin(held_out)]

    chosen = chosen.sort_values(["composer_top", "rel"]).reset_index(drop=True)
    rels = chosen["rel"].tolist()

    summary = {
        "manifest": str(manifest_path),
        "top_n_composers": int(top_n),
        "whitelist": list(include_composers),
        "whitelist_added_beyond_top_n": whitelist_added,
        "n_composers_chosen": int(chosen["composer_top"].nunique()),
        "n_sids": int(len(rels)),
        "n_eval_a_excluded": int(
            sum(1 for r in held_out if _composer_from_path(r) in selected)
        ),
        "per_composer_counts": chosen.groupby("composer_top")
        .size()
        .sort_values(ascending=False)
        .to_dict(),
    }
    return {"rels": rels, "summary": summary}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--manifest", default=DEFAULT_MANIFEST)
    ap.add_argument("--prodlike-dir", default=DEFAULT_PRODLIKE_DIR)
    ap.add_argument("--out-dir", default=DEFAULT_OUT_DIR)
    ap.add_argument("--top-n", type=int, default=100)
    ap.add_argument(
        "--include-composer",
        action="append",
        default=None,
        help=(
            "Composer name to include regardless of top-N rank. Repeat for "
            f"multiple. Default whitelist: {list(DEFAULT_INCLUDE_COMPOSERS)}."
        ),
    )
    ap.add_argument(
        "--dry-run",
        action="store_true",
        help="Print summary; don't write files.",
    )
    args = ap.parse_args()

    include = tuple(
        args.include_composer
        if args.include_composer is not None
        else DEFAULT_INCLUDE_COMPOSERS
    )
    result = build(
        Path(args.manifest),
        Path(args.prodlike_dir),
        args.top_n,
        include,
    )
    print(json.dumps(result["summary"], indent=2))

    if args.dry_run:
        return

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    train_path = out_dir / "train.list"
    with train_path.open("w") as f:
        f.write("# Generated by build_prodlike_4x_list.py\n")
        f.write(f"# Source: {args.manifest}\n")
        f.write(
            f"# Top {args.top_n} admitted composers + whitelist={list(include)},"
            f" excluding eval-B holdouts.\n"
        )
        f.write(
            f"# {result['summary']['n_sids']} SIDs across "
            f"{result['summary']['n_composers_chosen']} composers.\n"
        )
        for rel in result["rels"]:
            f.write(rel + "\n")
    print(f"\nWrote {train_path} ({result['summary']['n_sids']} SIDs).")

    prodlike_dir = Path(args.prodlike_dir)
    for eval_list in ["eval-A.list"] + sorted(
        p.name for p in prodlike_dir.glob("eval-B-*.list")
    ):
        dst = out_dir / eval_list
        if dst.exists() or dst.is_symlink():
            dst.unlink()
        rel_target = Path("..") / prodlike_dir.name / eval_list
        dst.symlink_to(rel_target)
        print(f"Linked {dst} -> {rel_target}")


if __name__ == "__main__":
    main()
