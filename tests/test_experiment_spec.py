class TestHvscVersionCheck(unittest.TestCase):
    """``preflight_check`` must abort when the HVSC tree's version
    differs from the tier's pin (or pass silently when the tree
    isn't on disk).
    """

    def setUp(self):
        self.tmpdir = Path(tempfile.mkdtemp())
        # Tier pins are generated into data/<tier>/HVSC_VERSION by the census
        # selector; point base.DATA_DIR at a temp dir carrying a "mini" pin so
        # these tests don't depend on a shipped pin.
        data_dir = self.tmpdir / "data"
        (data_dir / "mini").mkdir(parents=True)
        (data_dir / "mini" / "HVSC_VERSION").write_text("84\n")
        import preframr_experiments.base as _base  # noqa: WPS433

        p = patch.object(_base, "DATA_DIR", data_dir)
        p.start()
        self.addCleanup(p.stop)

    def tearDown(self):
        shutil.rmtree(self.tmpdir, ignore_errors=True)

    def _make_hvsc_tree(self, version: int) -> Path:
        root = self.tmpdir / "hvsc"
        (root / "DOCUMENTS").mkdir(parents=True)
        (root / "DOCUMENTS" / "HVSC.txt").write_text(
            "HIGH VOLTAGE SID COLLECTION\n\n"
            f"                              Release {version}\n\n"
        )
        return root

    def test_match_passes(self):
        from preframr_experiments.base import _hvsc_version_check

        hvsc = self._make_hvsc_tree(84)
        spec = ExperimentSpec(
            name="x",
            doc="d",
            tier="mini",
            arms=[Arm("a")],
            metrics=["alphabet_size"],
            hvsc_root=str(hvsc),
        )
        _hvsc_version_check(spec, logging.getLogger("test"))

    def test_mismatch_raises(self):
        from preframr_experiments.base import _hvsc_version_check

        hvsc = self._make_hvsc_tree(85)
        spec = ExperimentSpec(
            name="x",
            doc="d",
            tier="mini",
            arms=[Arm("a")],
            metrics=["alphabet_size"],
            hvsc_root=str(hvsc),
        )
        with self.assertRaises(RuntimeError) as ctx:
            _hvsc_version_check(spec, logging.getLogger("test"))
        self.assertIn("HVSC version mismatch", str(ctx.exception))

    def test_missing_tree_skips_silently(self):
        from preframr_experiments.base import _hvsc_version_check

        spec = ExperimentSpec(
            name="x",
            doc="d",
            tier="mini",
            arms=[Arm("a")],
            metrics=["alphabet_size"],
            hvsc_root=str(self.tmpdir / "does_not_exist"),
        )
        _hvsc_version_check(spec, logging.getLogger("test"))


