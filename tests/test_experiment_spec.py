class TestPinnedListsParse(unittest.TestCase):
    """Exercises the list-file parser against the actual pinned data
    -- catches a future change that breaks the comment-stripping or
    blank-line handling."""

    def test_smoke_list_parses(self):
        entries = smoke_paths()
        self.assertGreater(len(entries), 0)
        for e in entries:
            self.assertFalse(e.startswith("#"), f"comment leaked: {e!r}")
            relpath, subtune = parse_entry(e)
            self.assertTrue(relpath.endswith(".sid"), relpath)
            self.assertGreaterEqual(subtune, 1)

    @unittest.skipUnless(
        (DATA_DIR / "canonical" / "train.list").exists(),
        "canonical tier not pinned yet (generated by corpus/select.py from the census)",
    )
    def test_canonical_lists_parse(self):
        layout = canonical_paths()
        self.assertIn("train", layout)
        self.assertGreater(len(layout["train"]), 0)
        if "eval-A" in layout:
            self.assertGreater(len(layout["train"]), len(layout["eval-A"]))

    def test_read_list_strips_comments_and_blanks(self):
        with tempfile.NamedTemporaryFile("w", suffix=".list", delete=False) as f:
            f.write("# header line\n")
            f.write("\n")
            f.write("a/b/c.sid\t1\n")
            f.write("d/e/f.sid\t2  # composer note\n")
            f.write("   # leading space comment\n")
            tmp = f.name
        try:
            entries = read_list(Path(tmp))
            self.assertEqual([parse_entry(e) for e in entries], [("a/b/c.sid", 1), ("d/e/f.sid", 2)])
        finally:
            Path(tmp).unlink()


