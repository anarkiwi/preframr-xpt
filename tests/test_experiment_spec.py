class TestStageSids(unittest.TestCase):
    """``stage_sids`` stages each .sid under a per-composer bucket (colliding
    basenames across composers survive), returns ``(manifest_relpath, subtune)``
    rows rooted at work_dir, and a shared .sid yields one row per subtune."""

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp)
        self.src_root = self.tmp / "hvsc"
        self.work_dir = self.tmp / "work"
        self.logger = logging.getLogger("test")

    def _seed(self, rel: str, body: bytes) -> None:
        path = self.src_root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(body)

    def test_colliding_basenames_both_stage(self):
        self._seed("MUSICIANS/A/Foo/Bar.sid", b"FROM_FOO")
        self._seed("MUSICIANS/B/Baz/Bar.sid", b"FROM_BAZ")
        rows = stage_sids(
            ["MUSICIANS/A/Foo/Bar.sid\t1", "MUSICIANS/B/Baz/Bar.sid\t1"],
            self.src_root,
            "train",
            self.work_dir,
            self.logger,
        )
        self.assertEqual(
            sorted(rows),
            [("train/Baz/Bar.sid", 1), ("train/Foo/Bar.sid", 1)],
        )
        self.assertEqual(
            (self.work_dir / "train" / "Foo" / "Bar.sid").read_bytes(), b"FROM_FOO"
        )
        self.assertEqual(
            (self.work_dir / "train" / "Baz" / "Bar.sid").read_bytes(), b"FROM_BAZ"
        )

    def test_shared_sid_one_row_per_subtune(self):
        self._seed("MUSICIANS/A/Foo/Multi.sid", b"SID")
        rows = stage_sids(
            ["MUSICIANS/A/Foo/Multi.sid\t1", "MUSICIANS/A/Foo/Multi.sid\t3"],
            self.src_root,
            "train",
            self.work_dir,
            self.logger,
        )
        self.assertEqual(
            rows, [("train/Foo/Multi.sid", 1), ("train/Foo/Multi.sid", 3)]
        )

    def test_missing_sid_skipped(self):
        self._seed("MUSICIANS/A/Foo/Present.sid", b"P")
        rows = stage_sids(
            ["MUSICIANS/A/Foo/Present.sid\t1", "MUSICIANS/B/Baz/Absent.sid\t1"],
            self.src_root,
            "train",
            self.work_dir,
            self.logger,
        )
        self.assertEqual(rows, [("train/Foo/Present.sid", 1)])

    def test_write_manifest_roundtrips(self):
        path = self.work_dir / "train.manifest"
        path.parent.mkdir(parents=True, exist_ok=True)
        write_manifest(path, [("train/Foo/A.sid", 1), ("train/Bar/B.sid", 2)])
        self.assertEqual(
            [parse_entry(e) for e in read_list(path)],
            [("train/Foo/A.sid", 1), ("train/Bar/B.sid", 2)],
        )


